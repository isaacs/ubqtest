// Snapshots: `assert.snapshot(value)` compares a value with the
// text that an older run saved. One file for each test file, in
// `ubq-snapshots/`. Only `ubq --update` writes it. See
// docs/05-api.md, section 5.
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { inspect } from 'node:util'
import type { Diff } from './format.ts'
import { projectRoot } from './project.ts'

const HEADER = '// Snapshots of ubq. Do not edit this file. To write it: ubq --update <test file>\n'

let update = false
/** Called when the library loads, with the value from the runner. */
export const setUpdate = (on: boolean): void => {
  update = on
}

/** The snapshot file of a test file. Paths are from the project root. */
export const snapshotFile = (file: string): string => `ubq-snapshots/${file}.snap`

/** The text of a value. A string is its own text. */
export const snapshotText = (value: unknown): string =>
  typeof value === 'string' ? value : (
    inspect(value, {
      depth: Infinity,
      breakLength: 80,
      maxArrayLength: Infinity,
      maxStringLength: Infinity,
      sorted: true,
    })
  )

// The file is a list of entries in this form, with ` \ and ${ escaped:
//   exports[`group > name 1`] = `
//   text
//   `
const escape = (text: string): string => text.replace(/[`\\]|\$\{/g, m => '\\' + m)
const unescape = (text: string): string => text.replace(/\\([`\\]|\$\{)/g, '$1')
const ENTRY = /exports\[`((?:[^`\\]|\\.)*)`\] = `\n((?:[^`\\]|\\.)*)\n`\n/gs

let file: string | undefined
/** The entries of the file as they were at the start. */
let saved = new Map<string, string>()
/** The entries that this run wrote. */
const written = new Map<string, string>()
/** The count of snapshot assertions in each test. */
const counts = new Map<string, number>()

const load = (testFile: string): void => {
  if (file !== undefined) return
  file = testFile
  const path = join(projectRoot(), snapshotFile(testFile))
  if (!existsSync(path)) return
  for (const m of readFileSync(path, 'utf8').matchAll(ENTRY))
    saved.set(unescape(m[1]!), unescape(m[2]!))
}

export interface SnapshotResult {
  /** True if the value has the text of its snapshot, or the run writes snapshots. */
  ok: boolean
  /** For a failure: the message and the differences. */
  message?: string
  diffs?: Diff[]
  more?: number
}

/** Compares `value` with its snapshot. `id` is the ID of the test. */
export const checkSnapshot = (testFile: string, id: string, value: unknown): SnapshotResult => {
  load(testFile)
  const n = (counts.get(id) ?? 0) + 1
  counts.set(id, n)
  const key = `${id.slice(testFile.length + 3)} ${n}`
  const actual = snapshotText(value)
  if (update) {
    written.set(key, actual)
    return { ok: true }
  }
  const expected = saved.get(key)
  if (expected === undefined)
    return {
      ok: false,
      message: `no snapshot for this assertion (${key}). To write it: ubq --update '${id}'`,
    }
  if (expected === actual) return { ok: true }
  const a = actual.split('\n')
  const e = expected.split('\n')
  const diffs: Diff[] = []
  let more = 0
  for (let i = 0; i < Math.max(a.length, e.length); i++) {
    if (a[i] === e[i]) continue
    if (diffs.length === 4) more++
    else
      diffs.push({
        path: `line ${i + 1}`,
        actual: a[i] === undefined ? '(no line)' : JSON.stringify(a[i]),
        expected: e[i] === undefined ? '(no line)' : JSON.stringify(e[i]),
      })
  }
  return {
    ok: false,
    message: `expected the value to match its snapshot (${key}). If the new value is correct: ubq --update '${id}'`,
    diffs,
    more,
  }
}

/**
 * Writes the snapshot file, if the run writes snapshots. `ran` has
 * the tests that ran, `all` the tests of the file. A test that ran
 * keeps only what it wrote. A test that did not run keeps its
 * entries. Entries of tests that the file no longer has are removed.
 * Returns the count of entries that are new or different.
 */
export const saveSnapshots = (testFile: string, ran: Set<string>, all: Set<string>): number => {
  if (!update) return 0
  load(testFile)
  const testOf = (key: string): string => `${testFile} > ${key.replace(/ \d+$/, '')}`
  const entries = new Map(written)
  for (const [key, text] of saved) {
    const test = testOf(key)
    if (!ran.has(test) && all.has(test)) entries.set(key, text)
  }
  let changed = 0
  for (const [key, text] of written) if (saved.get(key) !== text) changed++
  const same = entries.size === saved.size && changed === 0
  if (same) return 0
  const path = join(projectRoot(), snapshotFile(testFile))
  if (!entries.size) rmSync(path, { force: true })
  else {
    const keys = [...entries.keys()].sort((x, y) => x.localeCompare(y, 'en', { numeric: true }))
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(
      path,
      HEADER +
        keys.map(k => `\nexports[\`${escape(k)}\`] = \`\n${escape(entries.get(k)!)}\n\`\n`).join(''),
    )
  }
  saved = entries
  return changed
}
