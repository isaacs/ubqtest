// Snapshots: assert.snapshot and ubq --update.
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { assert, cleanup, env, test } from 'ubqtest'
import { project } from './setup.ts'

test('a snapshot fails until --update writes it, and then compares text', () => {
  const p = project()
  cleanup(() => rmSync(p.dir, { recursive: true }))
  p.set('pass')
  const snap = join(p.dir, 'ubq-snapshots/snap.ts.snap')
  const out = (...args: string[]) => p.ubq(...args).out.replace(/ \(run \d+\)\n$/, '').split('\n')

  // No snapshot file: each assertion fails, and no file appears.
  assert.deepEqual(out('snap.ts').slice(0, 5), [
    'FAIL snap.ts > group > values',
    "  no snapshot for this assertion (group > values 1). To write it: ubq --update 'snap.ts > group > values'",
    '  at snap.ts:8:12',
    "  > assert.snapshot({ b: [1, 2], a: text, when: new Date(0), set: new Set(['x']) })",
    '  rerun: ubq snap.ts:7',
  ])
  assert.equal(existsSync(snap), false)

  assert.deepEqual(out('--update', 'snap.ts'), [
    'updated 3 snapshots: ubq-snapshots/snap.ts.snap',
    'pass: 0 failed, 2 passed',
  ])
  assert.equal(readFileSync(snap, 'utf8'), [
    '// Snapshots of ubq. Do not edit this file. To write it: ubq --update <test file>',
    '',
    'exports[`group > values 1`] = `',
    '{',
    "  a: 'one',",
    '  b: [ 1, 2 ],',
    "  set: Set(1) { 'x' },",
    '  when: 1970-01-01T00:00:00.000Z',
    '}',
    '`',
    '',
    'exports[`group > values 2`] = `',
    'line 1',
    'line one',
    'back\\`tick \\${x} \\\\ end',
    '`',
    '',
    'exports[`text 1`] = `',
    'one',
    '`',
    '',
  ].join('\n'))
  assert.deepEqual(out('snap.ts'), ['pass: 0 failed, 2 passed'])
  // An update with no change writes nothing.
  assert.deepEqual(out('--update', 'snap.ts'), ['pass: 0 failed, 2 passed'])

  // The values change.
  env({ SNAP_TEXT: 'two' })
  assert.deepEqual(out('snap.ts'), [
    'FAIL snap.ts > group > values',
    "  expected the value to match its snapshot (group > values 1). If the new value is correct: ubq --update 'snap.ts > group > values'",
    '  at snap.ts:8:12',
    "  > assert.snapshot({ b: [1, 2], a: text, when: new Date(0), set: new Set(['x']) })",
    '  line 2',
    '    actual:   "  a: \'two\',"',
    '    expected: "  a: \'one\',"',
    '  rerun: ubq snap.ts:7',
    '',
    'FAIL snap.ts > text',
    "  expected the value to match its snapshot (text 1). If the new value is correct: ubq --update 'snap.ts > text'",
    '  at snap.ts:14:10',
    '  > assert.snapshot(text)',
    '  line 1',
    '    actual:   "two"',
    '    expected: "one"',
    '  rerun: ubq snap.ts:13',
    '',
    'fail: 2 failed, 0 passed',
  ])
  // An update of one test keeps the snapshots of the other tests.
  assert.deepEqual(out('--update', 'snap.ts > text'), [
    'updated 1 snapshots: ubq-snapshots/snap.ts.snap',
    'pass: 0 failed, 1 passed, 1 not selected',
  ])
  assert.match(readFileSync(snap, 'utf8'), /a: 'one',[^]*\nexports\[`text 1`\] = `\ntwo\n`\n$/)
  assert.equal(p.ubq('snap.ts').last, 'fail: 1 failed, 1 passed')
  // With many files, in child processes.
  assert.equal(p.ubq('--update', 'snap.ts', 'flip.ts').out.split('\n')[0], 'updated 2 snapshots: ubq-snapshots/snap.ts.snap')
  assert.equal(p.ubq('snap.ts').last, 'pass: 0 failed, 2 passed')

  // A test that the file no longer has loses its snapshots.
  writeFileSync(join(p.dir, 'snap.ts'), readFileSync(join(p.dir, 'snap.ts'), 'utf8').replace("test('text'", "test('words'"))
  assert.equal(p.ubq('--update', 'snap.ts > words').out.split('\n')[0], 'updated 1 snapshots: ubq-snapshots/snap.ts.snap')
  const text = readFileSync(snap, 'utf8')
  assert.deepEqual([text.includes('exports[`text 1`]'), text.includes('exports[`words 1`]'), text.includes('`group > values 2`')], [false, true, true])

  // An update needs the tests by name.
  const usage = "ubq: --update needs the tests whose snapshots it writes, and no other option: ubq --update <file>, or ubq --update '<test id>'\n"
  assert.deepEqual([p.ubq('--update').err, p.ubq('--update', '--failed').err, p.ubq('--update').code], [usage, usage, 4])
})
